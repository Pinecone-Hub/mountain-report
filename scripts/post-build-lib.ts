// Pure helpers for scripts/post-build.ts (files Cloudflare Pages reads at the dist/ root).
// Node strip-types friendly: no enums, no parameter properties.

function trimSlashes(path: string): string {
  return path.replace(/^\/+|\/+$/g, "");
}

/** dist/_routes.json: only the Functions path invokes a Function. */
export function routesJson(basePath: string): string {
  return JSON.stringify({ version: 1, include: [`/${trimSlashes(basePath)}/api/*`], exclude: [] });
}

/** dist/_redirects: the report root goes to the default-language home (301). */
export function redirectsFile(basePath: string, defaultLanguage: string): string {
  const base = trimSlashes(basePath);
  if (base === "") throw new Error("basePath must name a folder");
  if (!/^[A-Za-z0-9-]+$/.test(defaultLanguage)) throw new Error(`invalid default language code "${defaultLanguage}"`);
  return `/${base}/ /${base}/${defaultLanguage}/ 301\n`;
}

/** The directory Pagefind indexes: dist/<basePath>. */
export function siteDirectory(basePath: string): string {
  return `dist/${trimSlashes(basePath)}`;
}

/** Pagefind files the site does not use: its ready-made search interfaces and the highlight script (the search page builds its own). */
export function unusedPagefindFiles(names: readonly string[]): string[] {
  return names.filter((name) => /^pagefind-(?:component-ui|modular-ui|ui|highlight)\.(?:js|css)$/.test(name));
}

/**
 * dist/_headers: Cloudflare Pages serves every file with X-Robots-Tag: noindex. Requests from the
 * public host reach Pages on the pages.dev host too, so the Worker removes this header again
 * (worker/src/index.ts); the pages.dev host itself stays out of search engines.
 */
export function headersFile(): string {
  return "/*\n  X-Robots-Tag: noindex\n";
}

/** True when a _headers file sets X-Robots-Tag: noindex for every path ("/*"). Cloudflare Pages syntax: a path line, then indented "Name: value" lines. */
export function headersHaveNoindex(text: string): boolean {
  let inAllPaths = false;
  for (const raw of text.split(/\r?\n/)) {
    if (raw.trim() === "" || raw.trim().startsWith("#")) continue;
    if (!/^\s/.test(raw)) {
      inAllPaths = raw.trim() === "/*";
      continue;
    }
    if (inAllPaths && /^\s*X-Robots-Tag\s*:\s*noindex\s*$/i.test(raw)) return true;
  }
  return false;
}

const regexEscape = (text: string): string => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/**
 * dist/<basePath>/.htaccess for Apache 2.4 (shared LAMP hosting): 404 page, root redirect to the
 * default language, index files, charset, MIME types and caching. Every block sits in an
 * <IfModule> guard so a host without the module still serves the site. Needs AllowOverride on the
 * folder (FileInfo, Indexes, Options is not needed).
 */
export function htaccessFile(basePath: string, defaultLanguage: string): string {
  const base = trimSlashes(basePath);
  if (base === "") throw new Error("basePath must name a folder");
  if (!/^[A-Za-z0-9._/-]+$/.test(base) || base.includes("..")) throw new Error(`invalid basePath "${basePath}" for .htaccess`);
  if (!/^[A-Za-z0-9-]+$/.test(defaultLanguage)) throw new Error(`invalid default language code "${defaultLanguage}"`);
  const b = regexEscape(`/${base}`);
  return `# Generated by scripts/post-build.ts from report.config.json. Do not edit by hand.
# Apache 2.4. Needs "AllowOverride All" (or FileInfo, Indexes, Limit) for this folder.

DirectoryIndex index.html
AddDefaultCharset UTF-8
ErrorDocument 404 /${base}/404.html

# The report root goes to the default-language home. Only the exact root: other URLs are untouched.
<IfModule mod_alias.c>
  RedirectMatch 301 ^${b}/$ /${base}/${defaultLanguage}/
</IfModule>

<IfModule mod_mime.c>
  AddType application/wasm .wasm
  AddType application/octet-stream .pf_meta .pf_index .pf_fragment .pagefind
  AddType text/csv .csv
  AddType image/svg+xml .svg
</IfModule>

# Hashed build assets never change: cache for a year. Pages are revalidated on every visit.
<IfModule mod_headers.c>
  <If "%{REQUEST_URI} =~ m#^${b}/_astro/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
  <ElseIf "%{REQUEST_URI} =~ m#(/|\\.html)$#">
    Header set Cache-Control "no-cache"
  </ElseIf>
</IfModule>
`;
}
